create extension if not exists vector;

-- -----------------------------------------------------------------------------
-- Problems and test cases (public, read-only for users)
-- -----------------------------------------------------------------------------

create table if not exists public.problems (
    id           bigint generated by default as identity primary key,
    title        text not null,
    description  text not null default '',
    topic        text,
    difficulty   text check (difficulty in ('Easy', 'Medium', 'Hard')),
    constraints  text,          -- one constraint per line (optional)
    starter_code text,          -- optional fallback; the frontend has built-in starters
    created_at   timestamptz not null default now()
);

create table if not exists public.test_cases (
    id              bigint generated by default as identity primary key,
    problem_id      bigint not null references public.problems (id) on delete cascade,
    input           text not null,   -- e.g.  nums=[2,7,11,15], target=9
    expected_output text not null,   -- e.g.  [0,1]
    created_at      timestamptz not null default now()
);

create index if not exists test_cases_problem_id_idx on public.test_cases (problem_id, id);

-- -----------------------------------------------------------------------------
-- Submissions (written by the backend with the service-role key)
-- -----------------------------------------------------------------------------

create table if not exists public.submissions (
    id         bigint generated by default as identity primary key,
    user_id    uuid not null references auth.users (id) on delete cascade,
    problem_id bigint not null references public.problems (id) on delete cascade,
    code       text not null,
    language   text not null,
    -- Queued | Running | Accepted | Wrong Answer | Compilation Error |
    -- Runtime Error | Time Limit Exceeded | Error
    status     text not null default 'Queued',
    passed     integer not null default 0,
    total      integer not null default 0,
    created_at timestamptz not null default now()
);

create index if not exists submissions_user_problem_idx
    on public.submissions (user_id, problem_id, created_at desc);

-- -----------------------------------------------------------------------------
-- RAG knowledge base (768 dims = EMBEDDING_DIMENSIONS in Backend/.env)
-- -----------------------------------------------------------------------------

create table if not exists public.knowledge_documents (
    id         bigint generated by default as identity primary key,
    title      text not null,
    content    text not null,
    category   text,
    source     text,
    metadata   jsonb not null default '{}'::jsonb,
    embedding  vector(768),
    created_at timestamptz not null default now()
);

create index if not exists knowledge_documents_embedding_idx
    on public.knowledge_documents using hnsw (embedding vector_cosine_ops);

create or replace function public.match_knowledge_documents(
    query_embedding vector(768),
    match_threshold float,
    match_count int
)
returns table (
    id bigint,
    title text,
    content text,
    category text,
    source text,
    metadata jsonb,
    similarity float
)
language sql stable
as $$
    select
        kd.id, kd.title, kd.content, kd.category, kd.source, kd.metadata,
        1 - (kd.embedding <=> query_embedding) as similarity
    from public.knowledge_documents kd
    where kd.embedding is not null
      and 1 - (kd.embedding <=> query_embedding) > match_threshold
    order by kd.embedding <=> query_embedding
    limit match_count;
$$;

-- -----------------------------------------------------------------------------
-- Row Level Security
-- The backend uses the service-role key, which bypasses RLS. These policies
-- protect the tables from direct access with the public (anon) key.
-- -----------------------------------------------------------------------------

alter table public.problems            enable row level security;
alter table public.test_cases          enable row level security;
alter table public.submissions         enable row level security;
alter table public.knowledge_documents enable row level security;

drop policy if exists "Problems are readable by everyone" on public.problems;
create policy "Problems are readable by everyone"
    on public.problems for select using (true);

drop policy if exists "Test cases are readable by everyone" on public.test_cases;
create policy "Test cases are readable by everyone"
    on public.test_cases for select using (true);

drop policy if exists "Users read their own submissions" on public.submissions;
create policy "Users read their own submissions"
    on public.submissions for select using (auth.uid() = user_id);

